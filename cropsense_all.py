def plot_spectral_profile(filepath, smooth=True):
    """
    Plots the Spectral Signature with optional smoothing (Interpolation).

    Parameters:
    - filepath (str): Path to the image file.
    - smooth (bool): If True, draws an interpolated curved line. If False, draws straight lines.
    """

    if not os.path.exists(filepath):
        return

    try:
        img_data = tiff.imread(filepath)
        y_real = []
        x_real = []

        is_125_bands = (img_data.ndim == 3 and img_data.shape[2] == 125)
        is_external = img_data.ndim == 3 and img_data.shape[2] > 1 and img_data.shape[2] > img_data.shape[0]
        num_bands = img_data.shape[2] if is_external else (img_data.shape[0] if img_data.ndim == 3 else 10)

        # 1. Intensity extraction (Y) and wavelength calculation (X)
        for i in range(num_bands):
            if is_external:
                y_real.append(np.mean(img_data[:, :, i]))
            elif img_data.ndim == 3:
                y_real.append(np.mean(img_data[i]))
            else: # Raw mosaic 2D
                r_off, c_off = i // 4, i % 4
                y_real.append(np.mean(img_data[r_off::4, c_off::4]))

            # Calculate X-axis
            if is_125_bands:
                x_real.append(450 + i * (500 / 124))
            else:
                wl_str = SILIOS_WAVELENGTHS.get(i, str(400 + i*5)).replace("nm", "")
                x_real.append(float(wl_str))

        y_real = np.array(y_real)
        x_real = np.array(x_real)

        # 2. Curve Smoothing
        x_smooth, y_smooth = x_real, y_real
        if smooth and len(x_real) > 3:
            x_smooth = np.linspace(x_real.min(), x_real.max(), 300)
            from scipy.interpolate import make_interp_spline
            spline = make_interp_spline(x_real, y_real, k=3) 
            y_smooth = spline(x_smooth)

        # 3. Display
        plt.figure(figsize=(10, 6))
        plt.plot(x_smooth, y_smooth, color='teal', linewidth=2.5, label='Interpolated Profile')

        # For 125 points, reduce marker size for readability
        marker_size = 15 if is_125_bands else 50
        plt.scatter(x_real, y_real, color='red', s=marker_size, zorder=5, label='Measured Bands')

        plt.title(f"Spectral Signature\n{os.path.basename(filepath)}")
        plt.xlabel("Wavelength (nm)")
        plt.ylabel("Mean Intensity")
        plt.legend()
        plt.grid(True, linestyle='--', alpha=0.5)
        plt.show()

    except Exception as e:
        print(f"❌ Error: {e}")

def prepare_hyperspectral_data(raw_hdr_path, dark_hdr_path, white_hdr_path, background='darken', min_brightness=0.03, max_brightness=0.85, ndvi_threshold=-0.1):
    """
    Memory (RAM) and speed-optimized version.
    Prevents Jupyter crashes on large 224-band files.
    """

    print("⏳ [1/4] Loading references (RAM Optimization)...")

    # 1. Load and immediately purge references to free RAM
    dark_img = envi.open(dark_hdr_path)
    dark_cube = np.array(dark_img[:, :, :], dtype=np.float32)
    dark_profile = np.mean(dark_cube, axis=0)
    del dark_cube  # Destroys the dark cube from memory
    gc.collect()   # Forces garbage collection

    white_img = envi.open(white_hdr_path)
    white_cube = np.array(white_img[:, :, :], dtype=np.float32)
    white_profile = np.mean(white_cube, axis=0)
    del white_cube # Destroys the white cube from memory
    gc.collect()

    # Denominator for calibration
    denominator = (white_profile - dark_profile)
    denominator[denominator == 0] = 1e-6


    print("⏳ [2/4] Loading RAW file and In-Place Calibration...")
    # 2. Load the main image, forcing a lightweight format (float32)
    raw_img = envi.open(raw_hdr_path)
    reflectance_cube = np.array(raw_img[:, :, :], dtype=np.float32)

    # IN-PLACE OPERATIONS: Modifies the existing array (saves ~3 GB of RAM!)
    reflectance_cube -= dark_profile
    reflectance_cube /= denominator
    np.clip(reflectance_cube, 0, 1, out=reflectance_cube)

    print("🌿 [3/4] Creating mask...")

    try:
        wavelengths = np.array(raw_img.metadata['wavelength'], dtype=float)
        xlabel = "Wavelength (nm)"
        band_nir = (np.abs(wavelengths - 840.0)).argmin()
        band_red = (np.abs(wavelengths - 650.0)).argmin()
        idx_vis_start = (np.abs(wavelengths - 400.0)).argmin()
        idx_vis_end = (np.abs(wavelengths - 700.0)).argmin()
    except KeyError:
        wavelengths = np.arange(reflectance_cube.shape[2])
        xlabel = "Spectral Band Number"
        band_nir, band_red = 162, 95
        idx_vis_start, idx_vis_end = 0, 110 

    # --- LIGHTWEIGHT MASKS ---
    brightness_visible = np.mean(reflectance_cube[:, :, idx_vis_start:idx_vis_end], axis=2)
    brightness_mask = (brightness_visible > min_brightness) & (brightness_visible < max_brightness)
    del brightness_visible # Cleanup

    band_nir_data = reflectance_cube[:, :, band_nir]
    band_red_data = reflectance_cube[:, :, band_red]
    ndvi = (band_nir_data - band_red_data) / (band_nir_data + band_red_data + 1e-6)
    ndvi_mask = ndvi > ndvi_threshold 
    del band_nir_data, band_red_data, ndvi # Cleanup

    plant_mask = brightness_mask & ndvi_mask
    del brightness_mask, ndvi_mask

    plant_pixels = reflectance_cube[plant_mask]
    if len(plant_pixels) == 0:
        print("⚠️ No plant detected. Adjust the thresholds.")
        return None

    print("📊 [4/4] Extracting signatures and Visual preparation...")
    mean_spectrum = np.mean(plant_pixels, axis=0)
    std_spectrum = np.std(plant_pixels, axis=0)

    rgb_image = reflectance_cube[:, :, [110, 70, 30]].copy()
    min_val = np.percentile(rgb_image, 2)
    max_val = np.percentile(rgb_image, 98)
    rgb_image = np.clip((rgb_image - min_val) / (max_val - min_val), 0, 1)

    if background == 'darken':
        rgb_image[~plant_mask] = rgb_image[~plant_mask] * 0.15
    elif background == 'purple':
        rgb_image[~plant_mask] = [0.6, 0.0, 0.8]

    rgb_final = np.rot90(rgb_image, k=1)

    print("✅ Data ready!")

    return {
        "rgb": rgb_final,
        "wavelengths": wavelengths,
        "mean": mean_spectrum,
        "std": std_spectrum,
        "xlabel": xlabel,
        "cube": reflectance_cube, # Now 2x lighter!
        "mask": plant_mask
    }

def separate_data(data, cut_line):
    """
    Splits a hyperspectral dataset into two along the scanning axis (lines).
    Recalculates the mean spectra and RGB images for each distinct part.
    """
    if data is None:
        print("⚠️ No data to separate.")
        return None, None

    print(f"✂️ Slicing the cube at line {cut_line}...")

    # Extract data from the dictionary
    full_cube = data["cube"]
    full_mask = data["mask"]
    wavelengths = data["wavelengths"]
    xlabel = data.get("xlabel", "Wavelength (nm)")

    # The RGB image that ALREADY has your background (it is currently rotated 90°)
    full_rgb_rotated = data["rgb"] 

    # 1. Temporarily undo the rotation (k=-1) to align it with the cube and mask
    full_rgb = np.rot90(full_rgb_rotated, k=-1)

    # ==========================================
    # SET 1: From the beginning (0) up to the cut_line
    # ==========================================
    cube_1 = full_cube[:cut_line, :, :]
    mask_1 = full_mask[:cut_line, :]
    rgb_1 = full_rgb[:cut_line, :, :]

    # Rotate the resulting piece back (k=1) for final display
    rgb_final_1 = np.rot90(rgb_1, k=1)

    # Recalculate spectra (only on the plant pixels of part 1)
    pixels_1 = cube_1[mask_1]
    mean_1 = np.mean(pixels_1, axis=0) if len(pixels_1) > 0 else np.zeros_like(wavelengths)
    std_1 = np.std(pixels_1, axis=0) if len(pixels_1) > 0 else np.zeros_like(wavelengths)

    data_1 = {
        "cube": cube_1,
        "mask": mask_1,
        "rgb": rgb_final_1,
        "wavelengths": wavelengths,
        "mean": mean_1,
        "std": std_1,
        "xlabel": xlabel
    }

    # ==========================================
    # SET 2: From the cut_line to the end
    # ==========================================
    cube_2 = full_cube[cut_line:, :, :]
    mask_2 = full_mask[cut_line:, :]
    rgb_2 = full_rgb[cut_line:, :, :]

    # Rotate the resulting piece back (k=1) for final display
    rgb_final_2 = np.rot90(rgb_2, k=1)

    # Recalculate spectra (only on the plant pixels of part 2)
    pixels_2 = cube_2[mask_2]
    mean_2 = np.mean(pixels_2, axis=0) if len(pixels_2) > 0 else np.zeros_like(wavelengths)
    std_2 = np.std(pixels_2, axis=0) if len(pixels_2) > 0 else np.zeros_like(wavelengths)

    data_2 = {
        "cube": cube_2,
        "mask": mask_2,
        "rgb": rgb_final_2,
        "wavelengths": wavelengths,
        "mean": mean_2,
        "std": std_2,
        "xlabel": xlabel
    }

    print("✅ Slicing complete! Two datasets created.")
    return data_1, data_2

