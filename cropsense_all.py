def show_index_map(data, index_name="NDVI"):
    """
    Calculates and displays the map of any hyperspectral index.
    Supported indices: NDVI, GNDVI, RVI, WI, NDWI, SIPI, PRI, ARI, CARI
    """
    if data is None:
        print("⚠️ No data provided.")
        return

    cube = data["cube"]
    wavelengths = data["wavelengths"]
    mask = data["mask"]
    index_name = index_name.upper()

    # --- Utility function to easily extract a band ---
    def get_band(target_nm):
        idx = np.argmin(np.abs(wavelengths - target_nm))
        return cube[:, :, idx]

    # --- 1. Band selection and pixel-by-pixel index calculation ---
    print(f"🗺️ Generating map for index: {index_name}")

    if index_name == "NDVI":
        b1, b2 = get_band(800), get_band(670)
        index_map = (b1 - b2) / (b1 + b2 + 1e-6)
        cmap_name = 'RdYlGn'

    elif index_name == "GNDVI":
        b1, b2 = get_band(800), get_band(550)
        index_map = (b1 - b2) / (b1 + b2 + 1e-6)
        cmap_name = 'RdYlGn'

    elif index_name == "RVI":
        b1, b2 = get_band(800), get_band(670)
        index_map = b1 / (b2 + 1e-6)
        cmap_name = 'viridis'

    elif index_name == "WI":
        b1, b2 = get_band(900), get_band(970)
        index_map = b1 / (b2 + 1e-6)
        cmap_name = 'Blues'

    elif index_name == "NDWI":
        b1, b2 = get_band(900), get_band(970)
        index_map = (b1 - b2) / (b1 + b2 + 1e-6)
        cmap_name = 'Blues_r'

    elif index_name == "SIPI":
        blue, red, nir = get_band(445), get_band(680), get_band(800)
        index_map = (nir - blue) / (nir - red + 1e-6)
        cmap_name = 'YlGn'

    elif index_name == "PRI":
        b1, b2 = get_band(531), get_band(570)
        index_map = (b2 - b1) / (b2 + b1 + 1e-6)
        cmap_name = 'PRGn'

    elif index_name == "ARI":
        red, nir = get_band(510), get_band(700)
        index_map = (1 / (red + 1e-6)) - (1 / (nir + 1e-6))
        cmap_name = 'magma'

    elif index_name == "CARI":
        red, nir = get_band(510), get_band(550)
        index_map = (1 / (red + 1e-6)) - (1 / (nir + 1e-6))
        cmap_name = 'magma'

    else:
        print(f"❌ Error: Index '{index_name}' is not recognized.")
        return

    # --- 2. Mask Application ---
    # Replaces non-plant pixels with NaN (which will become black)
    index_map_masked = np.where(mask, index_map, np.nan)

    # --- 3. Rotation to match your RGB image ---
    index_map_rotated = np.rot90(index_map_masked, k=1)

    # --- 4. Dynamic contrast management (Percentiles) ---
    # Since some indices (ARI, RVI) do not have limits from 0 to 1, 
    # we use the 2% and 98% percentiles to ignore extreme outlier values.
    valid_pixels = index_map_rotated[~np.isnan(index_map_rotated)]
    if len(valid_pixels) > 0:
        vmin = np.percentile(valid_pixels, 2)
        vmax = np.percentile(valid_pixels, 98)
    else:
        vmin, vmax = 0, 1

    # --- 5. Matplotlib Display ---
    plt.figure(figsize=(8, 8))

    # Palette configuration with black background for NaNs
    cmap = plt.colormaps.get_cmap(cmap_name).with_extremes(bad='black')

    im = plt.imshow(index_map_rotated, cmap=cmap, vmin=vmin, vmax=vmax)
    plt.colorbar(im, label=f"{index_name} Value", shrink=0.8)
    plt.title(f"Distribution Map: {index_name}")
    plt.axis('off')
    plt.tight_layout()
    plt.show()

