def create_custom_index(data, index_name, formula_str, bands_dict):
    """
    Calculates a custom hyperspectral index, applies the mask,
    and saves the formula in a text file.

    Parameters:
    - data: Dictionary generated by prepare_hyperspectral_data
    - index_name: Name of the index (e.g., "MY_SUPER_INDEX")
    - formula_str: Mathematical formula as text (e.g., "(L1 - L2) / L3")
    - bands_dict: Dictionary linking formula variables to nm (Max 4).
                  e.g., {"L1": 800, "L2": 670, "L3": 550}
    """
    if data is None:
        print("⚠️ No data provided.")
        return None

    # 1. Verification of the 4 wavelength limit
    if len(bands_dict) > 4:
        print("❌ Error: You specified more than 4 wavelengths. Maximum 4 allowed.")
        return None

    cube = data["cube"]
    wavelengths = data["wavelengths"]
    mask = data["mask"]

    # 2. Preparation of variables and save text
    local_vars = {}
    save_text = f"--- CUSTOM INDEX: {index_name.upper()} ---\n"
    save_text += f"Formula: {formula_str}\n\n"
    save_text += "Wavelengths used:\n"

    for var_name, target_nm in bands_dict.items():
        # Find the closest band in the cube
        idx = np.argmin(np.abs(wavelengths - target_nm))

        # Extract the corresponding 2D matrix
        local_vars[var_name] = cube[:, :, idx]

        save_text += f" - {var_name} : {target_nm} nm (Band n°{idx})\n"

    print(f"🧪 Calculating custom index '{index_name}'...")

    # 3. Secure mathematical calculation from text
    try:
        # np.errstate silently ignores division by zero from the background
        with np.errstate(divide='ignore', invalid='ignore'):
            # The evaluation (eval) applies your text formula directly to numpy matrices
            index_map = eval(formula_str, {"__builtins__": None}, local_vars)
    except Exception as e:
        print(f"❌ Syntax error in the formula: {e}")
        return None

    # 4. Save the text file
    file_path = f"{index_name}.txt"
    try:
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(save_text)
        print(f"📝 Explanations saved in: {file_path}")
    except IOError as e:
        print(f"⚠️ Unable to save the text file: {e}")

    # 5. Application of mask and rotation (like your other scripts)
    index_map_masked = np.where(mask, index_map, np.nan)
    index_map_rotated = np.rot90(index_map_masked, k=1)

    return index_map_rotated

def show_custom_map(index_map_rotated, index_name):
    """ Displays the map generated by create_custom_index """
    if index_map_rotated is None: return

    plt.figure(figsize=(8, 8))
    cmap = plt.cm.viridis.with_extremes(bad='black') # Black background

    # Dynamic calculation of contrasts to avoid outlier extreme values
    valid_pixels = index_map_rotated[~np.isnan(index_map_rotated)]
    vmin, vmax = np.percentile(valid_pixels, 2), np.percentile(valid_pixels, 98)

    im = plt.imshow(index_map_rotated, cmap=cmap, vmin=vmin, vmax=vmax)
    plt.colorbar(im, label=f"{index_name} Value", shrink=0.8)
    plt.title(f"Custom Map: {index_name}")
    plt.axis('off')
    plt.tight_layout()
    plt.show()

def calculate_mean_custom_index(data, formula_str, bands_dict):
    """
    Calculates the mean of a custom index over the entire plant.

    Parameters:
    - data: Dictionary generated by prepare_hyperspectral_data
    - formula_str: Mathematical formula as text (e.g., "(A - B) / C")
    - bands_dict: Dictionary of variables and wavelengths. (Max 4).
    """
    # Security in case the engine failed
    if data is None:
        print("⚠️ No data found")
        return None

    if len(bands_dict) > 4:
        print("❌ Error: You specified more than 4 wavelengths.")
        return None

    # 1. Automatic extraction from the dictionary
    cube = data["cube"]
    wavelengths = data["wavelengths"]
    mask = data["mask"]

    local_vars = {}

    print(f"📊 Calculating Custom Index Mean...")

    # 2. Extract only the plant pixels for each band
    for var_name, target_nm in bands_dict.items():
        band_idx = np.argmin(np.abs(wavelengths - target_nm))
        print(f"   -> {var_name} = {target_nm} nm (Band {band_idx})")

        # We extract the band and apply the mask directly [mask]
        # local_vars[var_name] becomes a 1D array containing only the plant pixels
        local_vars[var_name] = cube[:, :, band_idx][mask]

    # 3. Security: check if the mask is empty
    # We take the first variable at random to check the size
    first_variable = list(local_vars.values())[0]
    if len(first_variable) == 0:
        print("⚠️ The mask is empty, no pixel to analyze")
        return None

    # 4. Calculation of the formula on the 1D arrays
    try:
        with np.errstate(divide='ignore', invalid='ignore'):
            index_array = eval(formula_str, {"__builtins__": None}, local_vars)
    except Exception as e:
        print(f"❌ Syntax error in the formula: {e}")
        return None

    # 5. Return the mean
    return float(np.mean(index_array))

